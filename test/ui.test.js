import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm,mkdir} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {chromium} from 'playwright-core';
import {Runtime} from '../src/runtime.js';
import {serve} from '../src/server.js';
import {browserExecutable} from '../src/browser/session.js';
import {learnedMerchant} from './helpers/learned-merchant.js';
test('dashboard saves configuration, imports, validates twice, publishes and displays a new order',async t=>{
  const f=await learnedMerchant(),dir=await mkdtemp(join(tmpdir(),'whmcs-ui-')),runtime=await new Runtime(dir).open();
  const app=await serve({runtime,port:0}),browser=await chromium.launch({headless:true,executablePath:await browserExecutable()});
  t.after(async()=>{await browser.close();await app.close();await f.close();await rm(dir,{recursive:true,force:true});});
  const page=await browser.newPage({viewport:{width:1440,height:1100}});
  await page.goto('http://127.0.0.1:'+app.server.address().port);
  await page.getByRole('link',{name:'站点与购买配置',exact:true}).click();
  await page.locator('#config-json').fill(JSON.stringify({site:f.site,intent:f.intent,parameters:{},headless:true}));
  await page.locator('#save').click();await page.getByRole('status').filter({hasText:'配置已保存'}).waitFor();
  await page.getByRole('link',{name:'工作流仓库',exact:true}).click();
  await page.locator('#import').setInputFiles({name:'learned-workflow.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(f.workflow))});
  await page.locator('#workflow-rows tr').waitFor();
  await page.getByRole('button',{name:'试运行',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.run-row').length===1);
  await page.getByRole('button',{name:'试运行',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.run-row').length===2);
  assert.equal(f.state.submissions,0);
  await page.getByRole('button',{name:'发布',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#workflow-rows').textContent.includes('已验证'));
  await page.getByRole('button',{name:'真实下单',exact:true}).click();
  await page.getByRole('link',{name:'执行记录',exact:true}).click();
  await page.getByText('edge-s-order / v1 · 已创建订单',{exact:true}).waitFor();
  assert.equal(f.state.submissions,1);
  const screenshots=resolve('release/ui');await mkdir(screenshots,{recursive:true});
  if(await page.locator('#notice').isVisible())await page.locator('#notice').click();
  await page.getByRole('link',{name:'运行概况',exact:true}).click();
  await page.screenshot({path:join(screenshots,'dashboard-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.locator('main').evaluate(el=>el.getBoundingClientRect().right)<=391);
  await page.screenshot({path:join(screenshots,'dashboard-mobile.png'),fullPage:true});
});
